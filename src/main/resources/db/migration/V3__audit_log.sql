-- Denetim kaydı (audit log): kim, ne zaman, hangi kaydı değiştirdi. Yalnızca eklenir; uygulama güncelleme/silme yapmaz.
-- actor_id yabancı anahtar değildir: personel pasife alınsa ya da (başarısız girişte) hiç var olmasa da kayıt anlamını korur.
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP    NOT NULL,
    actor_id    BIGINT,
    actor_label VARCHAR(254) NOT NULL,
    actor_role  VARCHAR(20),
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(30),
    entity_id   VARCHAR(40),
    details     VARCHAR(500)
);
CREATE INDEX idx_audit_occurred ON audit_log (occurred_at);
CREATE INDEX idx_audit_actor ON audit_log (actor_label);
CREATE INDEX idx_audit_action ON audit_log (action);
