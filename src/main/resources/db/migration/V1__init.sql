-- Taşınabilir SQL (PostgreSQL ve H2): testler ve üretim aynı migrasyonları çalıştırır.

CREATE TABLE department (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE employee (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no VARCHAR(20)  NOT NULL UNIQUE,
    full_name       VARCHAR(150) NOT NULL,
    email           VARCHAR(254) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    title           VARCHAR(100),
    department_id   BIGINT REFERENCES department (id),
    hire_date       DATE         NOT NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX idx_employee_department ON employee (department_id);

CREATE TABLE leave_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT      NOT NULL REFERENCES employee (id),
    leave_type    VARCHAR(20) NOT NULL,
    start_date    DATE        NOT NULL,
    end_date      DATE        NOT NULL,
    business_days INT         NOT NULL,
    status        VARCHAR(20) NOT NULL,
    reason        VARCHAR(500),
    decided_by    BIGINT REFERENCES employee (id),
    decided_at    TIMESTAMP,
    created_at    TIMESTAMP   NOT NULL,
    CONSTRAINT chk_leave_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_leave_days CHECK (business_days > 0)
);
CREATE INDEX idx_leave_employee_dates ON leave_request (employee_id, start_date, end_date);
CREATE INDEX idx_leave_status ON leave_request (status);

CREATE TABLE asset (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag VARCHAR(50)  NOT NULL UNIQUE,
    name      VARCHAR(150) NOT NULL,
    category  VARCHAR(50)  NOT NULL,
    status    VARCHAR(20)  NOT NULL
);
CREATE INDEX idx_asset_status ON asset (status);

CREATE TABLE asset_assignment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id    BIGINT    NOT NULL REFERENCES asset (id),
    employee_id BIGINT    NOT NULL REFERENCES employee (id),
    assigned_at TIMESTAMP NOT NULL,
    returned_at TIMESTAMP,
    note        VARCHAR(300)
);
CREATE INDEX idx_assignment_asset ON asset_assignment (asset_id);
CREATE INDEX idx_assignment_employee ON asset_assignment (employee_id);
